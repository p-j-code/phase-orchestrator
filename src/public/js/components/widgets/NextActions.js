// "What next?" suggestion strip. Fetches ranked next-actions for the selected
// project and renders the first six: commands that map to a web verb become real
// buttons (wired through store.projectAction). Suggestions that do not have a
// safe direct web verb navigate to the relevant control surface or copy their
// exact command, so nothing that looks actionable is inert.

import { store } from '../../lib/store.js';
import { router, navigate, projectHash } from '../../lib/router.js';
import { api } from '../../lib/api.js';

// A deliberately small shell-like tokenizer. Suggestions are generated by the
// orchestrator, but treating them as unstructured prose made project names such
// as "resume-dashboard" or option values containing "next" dispatch real work.
// Quotes and backslash escapes are enough for the command forms emitted by the
// next-actions engine; nothing is evaluated.
export function commandTokens(command) {
  const input = String(command || '').trim();
  const tokens = [];
  let token = '';
  let quote = null;
  let escaped = false;
  const push = () => {
    if (token) tokens.push(token);
    token = '';
  };
  for (const char of input) {
    if (escaped) { token += char; escaped = false; continue; }
    if (char === '\\') { escaped = true; continue; }
    if (quote) {
      if (char === quote) quote = null;
      else token += char;
      continue;
    }
    if (char === '"' || char === "'") { quote = char; continue; }
    if (/\s/.test(char)) { push(); continue; }
    token += char;
  }
  if (escaped) token += '\\';
  push();
  return tokens;
}

function commandShape(cmd) {
  const tokens = commandTokens(cmd);
  const lower = tokens.map((token) => token.toLowerCase());
  const botCommand = (lower[0] || '').replace(/@[a-z0-9_]+$/i, '');
  const npmScript = lower[0] === 'npm' && lower[1] === 'run' ? (lower[2] || null) : null;
  const runAction = botCommand === '/run' ? (lower[2] || null) : null;
  return { tokens, lower, botCommand, npmScript, runAction };
}

function optionValue(lowerTokens, option) {
  for (let i = 0; i < lowerTokens.length; i++) {
    if (lowerTokens[i] === option) return lowerTokens[i + 1] || null;
    if (lowerTokens[i].startsWith(option + '=')) return lowerTokens[i].slice(option.length + 1) || null;
  }
  return null;
}

const DIRECT_VERBS = Object.freeze({
  go: 'go',
  resume: 'resume',
  next: 'next',
  abort: 'abort',
  pipeline: 'launch',
  launch: 'launch',
  'next-brief': 'next-brief',
  sync: 'sync',
});

// Map only an exact /run action token or exact npm script to a web verb. A
// project name, description, or option value can never select an action.
export function verbOf(cmd) {
  const shape = commandShape(cmd);
  if (shape.runAction) return DIRECT_VERBS[shape.runAction] || null;
  return shape.npmScript ? (DIRECT_VERBS[shape.npmScript] || null) : null;
}

export function tabOf(cmd) {
  const shape = commandShape(cmd);
  const { botCommand, npmScript, runAction, lower } = shape;

  if (botCommand === '/preview' || botCommand === '/files') return 'artifacts';
  if (botCommand === '/project') return 'overview';
  if (['/inbox', '/triage', '/bugs_inbox', '/bug_capture', '/capture', '/bug', '/req'].includes(botCommand)) return 'inbox';
  if (botCommand === '/download') return 'operations';
  if (botCommand === '/run') {
    if (runAction === 'brief') return 'brief';
    if (['audit', 'roadmap', 'bugs', 'guide', 'review', 'handoff', 'qa', 'qa-handoff',
      'validate', 'retry-phase', 'ship', 'package', 'reset-brief'].includes(runAction)) return 'operations';
    return null;
  }

  if (!npmScript) return null;
  if (['req', 'bug', 'triage'].includes(npmScript)) return 'inbox';
  if (npmScript === 'brief') return 'brief';
  if (npmScript === 'config') return 'config';
  // Guide's bug-plan mode still requires a CLI workflow. Its exact plan mode
  // has an equivalent control on Operations.
  if (npmScript === 'guide') return optionValue(lower, '--task') === 'plan' ? 'operations' : null;
  if (['audit', 'roadmap', 'bugs', 'qa-handoff', 'validate', 'retry-phase', 'ship',
    'package', 'review', 'handoff', 'qa', 'reset-brief'].includes(npmScript)) return 'operations';
  return null;
}

export default {
  name: 'NextActions',
  data() {
    return {
      items: null,   // [{id,label,description,kind,cmd,category,priority}] | null (error / not loaded)
      loading: true,
      error: '',
      requestSeq: 0,
      copyFallback: '',
      copyFallbackLabel: '',
    };
  },
  computed: {
    name() { return router.project; },
    runStatus() {
      const d = store.state.detail;
      return d && d.autoRun ? d.autoRun.status : null;
    },
    actions() {
      const items = Array.isArray(this.items) ? this.items.slice(0, 6) : [];
      let primaryTaken = false;
      return items.map((it) => {
        const verb = verbOf(it.cmd);
        const targetTab = verb ? null : tabOf(it.cmd);
        const primary = !!verb && !primaryTaken;
        if (verb) primaryTaken = true;
        return { ...it, verb, targetTab, primary };
      });
    },
  },
  watch: {
    runStatus() { this.fetch(); },
    // widget instance can survive a project switch — reset and refetch
    name() { this.items = null; this.fetch(); },
  },
  mounted() { this.fetch(); },
  methods: {
    async fetch() {
      if (!this.name) { this.items = null; this.loading = false; return; }
      const name = this.name;
      const seq = ++this.requestSeq;
      this.loading = true;
      this.error = '';
      try {
        const rows = await api('GET', '/projects/' + encodeURIComponent(name) + '/next-actions');
        if (this.name === name && seq === this.requestSeq) this.items = Array.isArray(rows) ? rows : [];
      } catch (e) {
        if (this.name === name && seq === this.requestSeq) { this.items = null; this.error = e.message; }
      } finally {
        if (this.name === name && seq === this.requestSeq) this.loading = false;
      }
    },
    btnClass(a) {
      if (a.verb === 'abort') return 'btn-danger';
      return a.primary ? 'btn-primary' : '';
    },
    isBusy(a) {
      return !!(a.verb && store.state.busy[a.verb + ':' + this.name]);
    },
    async run(a) {
      this.copyFallback = '';
      this.copyFallbackLabel = '';
      if (a.verb) { store.projectAction(this.name, a.verb); return; }
      if (a.targetTab) { navigate(projectHash(this.name, a.targetTab)); return; }
      if (!a.cmd) return;
      try {
        if (!navigator.clipboard?.writeText) throw new Error('Clipboard API unavailable');
        await navigator.clipboard.writeText(a.cmd);
        store.toast('Command copied', 'info');
      } catch {
        this.copyFallback = String(a.cmd);
        this.copyFallbackLabel = a.label || 'suggested action';
        store.toast('Automatic copy is unavailable — select the command shown below', 'warn');
        await this.$nextTick();
        const field = this.$refs.copyFallback;
        field?.focus();
        field?.select();
      }
    },
    closeCopyFallback() {
      this.copyFallback = '';
      this.copyFallbackLabel = '';
    },
  },
  template: `
    <div v-if="loading" class="skeleton" style="height:32px"></div>
    <div v-else-if="error" class="banner banner-warn">
      <span class="grow">Could not load next actions: {{ error }}</span>
      <button class="btn btn-sm" @click="fetch">Retry</button>
    </div>
    <div v-else-if="actions.length" class="row-wrap">
      <span class="label nowrap">Next</span>
      <template v-for="a in actions" :key="a.id">
        <button v-if="a.verb" class="btn btn-sm" :class="btnClass(a)"
                :title="a.description || a.cmd" :disabled="isBusy(a)" @click="run(a)">
          <span v-if="isBusy(a)" class="spinner"></span> {{ a.label }}
        </button>
        <button v-else class="btn btn-ghost btn-sm" @click="run(a)"
                :aria-label="(a.targetTab ? 'Open ' + a.targetTab + ' controls for ' : 'Copy command for ') + a.label"
                :title="(a.description || '') + (a.cmd ? '\\n' + a.cmd : '')">
          {{ a.label }} <span aria-hidden="true">{{ a.targetTab ? '→' : '⧉' }}</span>
        </button>
      </template>
    </div>
    <div v-if="copyFallback" class="banner banner-warn col" role="region"
         aria-label="Manual command copy" aria-live="polite" style="align-items: stretch">
      <div class="row-wrap">
        <span class="grow small">Automatic copy is unavailable. Select and copy this command for {{ copyFallbackLabel }}:</span>
        <button class="btn btn-ghost btn-sm" @click="closeCopyFallback" aria-label="Close manual command copy">×</button>
      </div>
      <textarea ref="copyFallback" class="input mono small" :value="copyFallback" readonly rows="3"
                aria-label="Command to copy manually" @focus="$event.target.select()" @click="$event.target.select()"></textarea>
    </div>
  `,
};
